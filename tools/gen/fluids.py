def _noise(seed, h=16, w=16, blur=2):
    a = np.random.default_rng(seed).random((h, w))
    for _ in range(blur):
        a = (np.roll(a, 1, 0) + np.roll(a, -1, 0) + np.roll(a, 1, 1) + np.roll(a, -1, 1) + a * 2) / 6
    return (a - a.min()) / (a.max() - a.min() + 1e-9)


def _rgba(gray, alpha):
    out = np.zeros(gray.shape + (4,), np.uint8)
    out[..., 0] = out[..., 1] = out[..., 2] = np.clip(gray, 0, 255).astype(np.uint8)
    out[..., 3] = np.clip(alpha, 0, 255).astype(np.uint8)
    return Image.fromarray(out, 'RGBA')


def fluid_strip(kind):
    """Grey animated strip (tinted by the fluid colour): liquid — slow ripples, gas — swirling haze, solid — static."""
    frames = 1 if kind == 'solid' else 32
    base = _noise({'liquid': 51, 'gas': 52, 'solid': 53}[kind], 16 * 2, 16, blur=3)
    im = np.zeros((16 * frames, 16))
    for f in range(frames):
        shift = np.roll(base, f, 0)[:16] if kind == 'liquid' else np.roll(np.roll(base, f, 0), f // 2, 1)[:16]
        if kind == 'liquid':
            im[16 * f:16 * f + 16] = 200 + 55 * shift
        elif kind == 'gas':
            im[16 * f:16 * f + 16] = 215 + 40 * shift
        else:
            im[16 * f:16 * f + 16] = 190 + 50 * shift
    alpha = np.full(im.shape, 255 if kind != 'gas' else 200)
    return _rgba(im, alpha), frames


def capsule_art():
    cell = np.array(Image.open(os.path.join(TEX, 'cells', 'cell.png')).convert('RGBA'))
    over = np.array(Image.open(os.path.join(TEX, 'cells', 'cell_OVERLAY.png')).convert('RGBA'))
    empty = over.copy()
    m = cell[..., 3] > 0
    empty[m] = (205, 225, 235, 110)
    # universal: tin can with a blue-grey band and darker caps (IC2 universal fluid cell)
    uni = over.copy().astype(float)
    sh = uni[..., 3] > 0
    uni[sh, 0] *= 0.80
    uni[sh, 1] *= 0.88
    uni[sh, 2] = np.minimum(255, uni[sh, 2] * 1.05 + 10)
    for y in (1, 2, 13, 14):
        uni[y, sh[y], :3] *= 0.6
    for y in (7, 8):
        row = sh[y]
        uni[y, row, :3] = (70, 110, 170)
    uni = uni.astype(np.uint8)
    uni_empty = uni.copy()
    uni_empty[m] = (205, 225, 235, 110)
    return {'capsule': Image.fromarray(empty, 'RGBA'), 'capsule_fluid': Image.fromarray(cell, 'RGBA'),
            'capsule_overlay': Image.fromarray(over, 'RGBA'), 'universal_capsule': Image.fromarray(uni_empty, 'RGBA'),
            'universal_capsule_overlay': Image.fromarray(uni, 'RGBA')}


def tank_art(rgb, seed):
    n = _noise(seed)
    c = np.array(rgb, float)
    metal = c[None, None, :] * (0.75 + 0.35 * n[..., None])
    side = metal.copy()
    glass = np.array((150, 190, 205), float)
    side[3:13, 4:12] = glass * (0.85 + 0.25 * n[3:13, 4:12, None])
    side[3:13, 5] = side[3:13, 5] * 0.6 + 255 * 0.4  # glint
    for y in (2, 13):
        side[y, 3:13] *= 0.55
    side[2:14, 3] *= 0.55
    side[2:14, 12] *= 0.55
    side[[0, 15], :] *= 0.6
    side[:, [0, 15]] *= 0.6
    top = metal.copy()
    yy, xx = np.mgrid[0:16, 0:16]
    ring = np.abs(np.hypot(xx - 7.5, yy - 7.5) - 4.5) < 0.8
    top[ring] *= 0.55
    top[[0, 15], :] *= 0.6
    top[:, [0, 15]] *= 0.6
    mk = lambda a: Image.fromarray(np.dstack([np.clip(a, 0, 255), np.full((16, 16), 255)]).astype(np.uint8), 'RGBA')
    return mk(side), mk(top)


def pretty(fid):
    return ' '.join(w.capitalize() for w in fid.replace('.', ' ').replace('_', ' ').split())


def gt_fluid_table():
    """[(entry for iis/gt_fluids.json, en, ru)]: GT5 fluids + IC2 replacements. Also read by chem.py, which runs before generate()."""
    src = json.load(open(os.path.join(HERE, '..', '..', 'reference', 'original', 'gt5_fluids.json'), encoding='utf-8'))
    rows, seen = [], set()
    for f in src:
        if f['id'] in SKIP_FLUIDS:
            continue
        rid = f['id'].replace('.', '_').replace('-', '_').lower()
        if rid in seen:
            continue
        seen.add(rid)
        r, gg, b = f['rgb']
        entry = {'id': rid, 'state': f['state'], 'temperature': f['temperature'], 'color': (r << 16) | (gg << 8) | b}
        if f.get('material'):
            entry['material'] = f['material']
        en = f['en'] if f['en'] != f['id'] else pretty(f['id'])
        rows.append((entry, en, f.get('ru') or en))
    for rid, en, ru_, state, temp, (r, gg, b) in IC2_FLUIDS:
        rows.append(({'id': rid, 'state': state, 'temperature': temp, 'color': (r << 16) | (gg << 8) | b}, en, ru_))
    return rows


def generate(g):
    write, A, D, lang, block_tags, RES = g['write'], g['A'], g['D'], g['lang'], g['block_tags'], g['RES']
    item_tags = g.get('item_tags')

    def name(key, en, ru):
        lang['en_us'][key] = en
        lang['ru_ru'][key] = ru

