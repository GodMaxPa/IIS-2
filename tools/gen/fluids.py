        write(os.path.join(A, 'items', pid + '.json'), {'model': {'type': 'minecraft:model', 'model': f'{NS}:item/{pid}',
              'tints': [{'type': 'minecraft:constant', 'value': color}]}})
        loot(pid)
        block_tags.setdefault('iis:mineable/wrench', []).append(f'{NS}:{pid}')
        name(f'block.{NS}.{pid}', en, ru)
        name(f'block.{NS}.{pid}.tooltip.0', f'Fluid Capacity: {cap * 20} L/sec', f'Пропускная способность: {cap * 20} л/с')
        name(f'block.{NS}.{pid}.tooltip.1', f'Heat Limit: {heat} K', f'Предел температуры: {heat} K')
        if gas:
            name(f'block.{NS}.{pid}.tooltip.2', 'Gas proof', 'Не пропускает газ')
        else:
            name(f'block.{NS}.{pid}.tooltip.2', 'Not gas proof: gases leak out', 'Пропускает газ: газы утекают')
        # crafting: only where the plate exists (other materials come with their metallurgy)
        if size in PIPE_CRAFT and mat in ('wood', 'copper', 'stainless_steel'):
            pat, cnt = PIPE_CRAFT[size]
            key = ({'P': '#minecraft:planks', 'h': '#iis:tools/soft_hammer', 'w': '#iis:tools/saw'} if mat == 'wood'
                   else {'P': f'#c:plates/{mat}', 'h': '#iis:tools/hammer', 'w': '#iis:tools/wrench'})
