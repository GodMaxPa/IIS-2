    n_pipes = 0
    allf = ('north', 'south', 'east', 'west', 'up', 'down')
    for pid, mat, cap, heat, thick, color, gas, iset, en, ru in pipe_specs():
        size = pid.split('_')[1]
        add_item_tag(f'iis:pipes/{size}/{mat}', f'{NS}:{pid}')
        add_item_tag('iis:pipes', f'{NS}:{pid}')
        if pid in EXISTING_PIPES:
            continue
        n_pipes += 1
        tsize = {'tiny': 'small', 'huge': 'large'}.get(size, size)
        side_tex, end_tex = f'{NS}:block/pipe/{iset.lower()}_side', f'{NS}:block/pipe/{iset.lower()}_{tsize}'
        shutil.copy(os.path.join(TEX, 'pipes', iset, 'pipeSide.png'), tex(f'block/pipe/{iset.lower()}_side.png'))
        shutil.copy(os.path.join(TEX, 'pipes', iset, f'pipe{tsize.capitalize()}.png'), tex(f'block/pipe/{iset.lower()}_{tsize}.png'))
        lo, hi = (16 - thick) / 2, (16 + thick) / 2
        txs = {'particle': side_tex, 'side': side_tex, 'end': end_tex}
        write(os.path.join(A, 'models', 'block', pid + '_core.json'), {'parent': 'minecraft:block/block', 'textures': txs,
              'elements': [{'from': [lo, lo, lo], 'to': [hi, hi, hi], 'faces': {f: {'texture': '#side', 'tintindex': 0} for f in allf}}]})
        write(os.path.join(A, 'models', 'block', pid + '_arm.json'), {'parent': 'minecraft:block/block', 'textures': txs,
              'elements': [{'from': [lo, lo, 0], 'to': [hi, hi, lo],
                            'faces': {'north': {'texture': '#end', 'tintindex': 0, 'cullface': 'north'},
                                      'east': {'texture': '#side', 'tintindex': 0}, 'west': {'texture': '#side', 'tintindex': 0},
                                      'up': {'texture': '#side', 'tintindex': 0}, 'down': {'texture': '#side', 'tintindex': 0}}}]})
        rot = {'north': {}, 'south': {'y': 180}, 'east': {'y': 90}, 'west': {'y': 270}, 'up': {'x': 270}, 'down': {'x': 90}}
