    /** Текст книги зала: по названию без номера; у неизвестного зала — его краткое описание. */
    public static String text(String numberedTitle, String about) {
        String title = numberedTitle.replaceFirst("^\\d+\\. ", "");
        String t = TEXT.get(title);
        return title + "\n\n" + (t == null ? about : t.strip());
    }

    /** Разбить текст на страницы книги: по абзацам и словам, не больше {@code LIMIT} знаков на страницу. */
    public static List<String> pages(String text) {
        final int limit = 230;
        List<String> pages = new ArrayList<>();
        StringBuilder cur = new StringBuilder();
        for (String para : text.split("\n\n")) {
            String par = para.replace('\n', ' ').replaceAll(" +", " ").strip();
            if (par.isEmpty()) continue;
            if (cur.length() > 0 && cur.length() + 2 + par.length() > limit) {
                pages.add(cur.toString());
                cur = new StringBuilder();
            }
            if (cur.length() > 0) cur.append("\n\n");
            for (String word : par.split(" ")) {
                if (cur.length() + 1 + word.length() > limit) {
                    pages.add(cur.toString().strip());
                    cur = new StringBuilder();
                }
                if (cur.length() > 0 && cur.charAt(cur.length() - 1) != '\n') cur.append(' ');
                cur.append(word);
            }
        }
        if (cur.length() > 0) pages.add(cur.toString());
        return pages;
    }
